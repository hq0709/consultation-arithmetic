"""Every number the radiology manuscript reports, formatted from the analysis outputs.

  python experiments/imaging_v2_analysis.py {A,B,C,M,D}   # first
  python experiments/radiology_numbers.py                  # -> paper/radiology/numbers.md
Intervals are item bootstrap 95% CIs as computed in experiments/imaging_v2_analysis.py.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
R = ROOT / "results"
J = {k: json.loads((R / f"imaging_v2_{k}.json").read_text()) for k in "ABCMD" if (R / f"imaging_v2_{k}.json").exists()}
MODELS = ["gpt-5-mini", "gemini-3.7-flash", "claude-haiku-4-5-20251001", "qwen3.8-flash"]
NAME = {"gpt-5-mini": "GPT-5 mini", "gemini-3.7-flash": "Gemini 3.7 Flash", "claude-haiku-4-5-20251001": "Claude Haiku 4.5",
        "qwen3.8-flash": "Qwen 3.8 Flash", "medgemma-4b": "MedGemma 4B", "qwen3-vl-8b": "Qwen3-VL 8B",
        "qwen2-vl-7b": "Qwen2-VL 7B", "huatuogpt-vision-7b": "HuatuoGPT-Vision 7B", "llava-1.5-7b": "LLaVA-1.5 7B"}
SETS = {"vqarad": "VQA-RAD", "slake": "SLAKE", "mxqa_mm_rad": "MedXpertQA-MM"}
out = []


def f(ci, nd=1, sign=False):
    if not ci:
        return "–"
    if isinstance(ci, (int, float)):
        return f"{ci:+.{nd}f}" if sign else f"{ci:.{nd}f}"
    e, lo, hi = ci
    fmt = (lambda v: f"{v:+.{nd}f}") if sign else (lambda v: f"{v:.{nd}f}")
    return f"{fmt(e)} [{fmt(lo)}, {fmt(hi)}]"


def table(head, rows):
    out.append("| " + " | ".join(head) + " |")
    out.append("|" + "---|" * len(head))
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    out.append("")


A = J.get("A", {})
out += ["# Numbers for the radiology manuscript", "",
        "All intervals: item bootstrap 95% CI. pp, percentage points. Generated by experiments/radiology_numbers.py.", ""]

out += ["## A0. Reading panels (original images)", ""]
rows = []
for s, sl in SETS.items():
    for m in MODELS:
        d = A.get(f"{m}|{s}")
        if not d:
            continue
        r0, dis, pd = d.get("real") or {}, d.get("discussion") or {}, d.get("paired") or {}
        u0, uf = r0.get("unanimity_round0") or {}, dis.get("unanimity_final") or {}
        rows.append([sl, NAME[m], str(d["n_items"]), f(r0.get("single")), f(r0.get("panel9")), f(dis.get("acc9")),
                     f(pd.get("panel9_minus_single"), sign=True), f(pd.get("disc9_minus_single"), sign=True),
                     f(r0.get("phi"), 3), f(r0.get("neff"), 2),
                     f(u0.get("unanimity")), f(u0.get("wrong_given_unanimous")),
                     f(dis.get("phi_last"), 3), f(uf.get("unanimity")), f(uf.get("wrong_given_unanimous"))])
table(["Set", "Model", "n", "Single (%)", "Panel 9 (%)", "Discussion 9 (%)", "Panel 9 − single (pp)",
       "Discussion 9 − single (pp)", "φ round 0", "N_eff", "Unanimous r0 (%)", "Wrong if unanimous r0 (%)",
       "φ final", "Unanimous final (%)", "Wrong if unanimous final (%)"], rows)

out += ["## A1. Graded evidence", ""]
rows = []
for s, sl in SETS.items():
    for m in MODELS:
        d = A.get(f"{m}|{s}")
        if not d:
            continue
        lv = [d.get(k) or {} for k in ("real", "res256", "res128", "blank")]
        pd = d.get("paired") or {}
        rows.append([sl, NAME[m]] + [f(x.get("single")) for x in lv] + [f(x.get("phi"), 3) for x in lv] +
                    [f(pd.get("single_real_minus_blank"), sign=True), f(pd.get("panel9_real_minus_blank"), sign=True),
                     f(lv[3].get("abstention_pct")), f(lv[3].get("phi_answered"), 3)])
table(["Set", "Model", "Single ≤1024", "Single 256", "Single 128", "Single gray", "φ ≤1024", "φ 256", "φ 128", "φ gray",
       "Single real − gray (pp)", "Panel 9 real − gray (pp)", "Abstention gray (%)", "φ gray, answered only"], rows)

out += ["## A1. Prior decomposition (reader answers of the independent panel of 9, % of answers)", ""]
rows = []
for s, sl in SETS.items():
    for m in MODELS:
        p = (A.get(f"{m}|{s}") or {}).get("prior_decomposition")
        if not p:
            continue
        rows.append([sl, NAME[m], f(p["prior_right_stays_right"]), f(p["image_corrects_prior"]), f(p["image_misleads_prior"]),
                     f(p["prior_wrong_stays_wrong"]), str(p["consensus_errors"]),
                     f(p.get("consensus_errors_matching_blank_majority"))])
table(["Set", "Model", "Right with and without image", "Right only with image", "Wrong only with image",
       "Wrong with and without image", "Consensus errors (n)", "Consensus errors = gray-image majority (%)"], rows)

out += ["## A2. Region occlusion (SLAKE-target)", ""]
rows = []
for m in MODELS:
    t = A.get(f"{m}|slake_target")
    if t:
        rows.append([NAME[m], "API, panel readers", f(t.get("panel9_occ_target_reader_flip")), f(t.get("panel9_occ_control_reader_flip")),
                     f(t.get("panel9_region_dependence"), sign=True), f(t.get("single_occ_target_flip")),
                     f(t.get("single_occ_control_flip")), f(t.get("single_region_dependence"), sign=True)])
D = J.get("D", {})
for m in D.get("models", []):
    t = D.get(f"{m}|slake_target") or {}
    if t.get("flip_target"):
        rows.append([NAME[m], "open weight", f(t["flip_target"]), f(t["flip_control"]), f(t["region_dependence_flip"], sign=True),
                     "", "", ""])
table(["Model", "Arm", "Target flip (%)", "Control flip (%)", "Region dependence (pp)", "Single target flip (%)",
       "Single control flip (%)", "Single region dependence (pp)"], rows)

out += ["## A3. Same question, different image (SLAKE-pairs, 200 pairs)", ""]
rows = []
for m in MODELS:
    p = A.get(f"{m}|slake_pairs")
    if p:
        rows.append([NAME[m], f(p.get("single_both_correct")), f(p.get("single_answers_differ")), f(p.get("panel9_both_correct")),
                     f(p.get("panel9_answers_differ")), f(p.get("reader_answers_differ"))])
for m in D.get("models", []):
    p = D.get(f"{m}|slake_pairs")
    if p:
        rows.append([NAME[m] + " (open weight)", f(p.get("both_correct")), f(p.get("answers_differ")), "", "", ""])
table(["Model", "Single: both correct (%)", "Single: answers differ (%)", "Panel 9: both correct (%)",
       "Panel 9: answers differ (%)", "Readers: answers differ (%)"], rows)

out += ["## Discussion: correct round-0 answers abandoned by the final round", ""]
rows = []
for s, sl in SETS.items():
    for m in MODELS:
        c = ((A.get(f"{m}|{s}") or {}).get("discussion") or {}).get("conformity")
        if not c:
            continue
        rows.append([sl, NAME[m], f(c.get("right_to_wrong_image_dependent")), f(c.get("right_to_wrong_prior_consistent")),
                     f(c.get("right_to_wrong_difference"), sign=True), f(c.get("right_to_wrong_minority")),
                     f(c.get("right_to_wrong_majority")), f(c.get("image_dependent_correct_in_minority_pct")),
                     f(c.get("prior_consistent_correct_in_minority_pct")),
                     f"{c.get('n_right_image_dependent')}/{c.get('n_right_prior_consistent')}"])
table(["Set", "Model", "Abandoned, from image (%)", "Abandoned, same as prior (%)", "Difference (pp)",
       "Abandoned, in minority (%)", "Abandoned, in majority (%)", "From image: in minority (%)",
       "Same as prior: in minority (%)", "n correct (image/prior)"], rows)

B = J.get("B", {})
out += ["## B. Seeing and judging: reader accuracy (%) and φ", ""]
rows = []
for s, sl in SETS.items():
    for r in MODELS[:3]:
        row = (B.get(s) or {}).get(r) or {}
        dr = row.get("direct") or {}
        cells = [f((row.get(f"{p}|own") or {}).get("reader_acc")) for p in MODELS[:3]]
        rows.append([sl, NAME[r]] + cells + [f(dr.get("reader_acc")), f(dr.get("phi"), 3),
                     f((row.get(f"{r}|own") or {}).get("phi"), 3), f((row.get(f"{r}|shared") or {}).get("phi"), 3),
                     f((row.get(f"{r}|own") or {}).get("panel_acc")), f(dr.get("panel_acc"))])
table(["Set", "Reasoner", "Reports by GPT-5 mini", "Reports by Gemini", "Reports by Haiku", "Image itself",
       "φ image", "φ own reports (same model)", "φ shared report", "Panel acc, own reports", "Panel acc, image"], rows)
rows = []
for r in MODELS[:3]:
    row = (B.get("slake") or {}).get(r) or {}
    for p in MODELS[:3]:
        e = row.get(f"{p}|own") or {}
        if e.get("errors_report_misses_target_pct") is not None:
            rows.append([NAME[r], NAME[p], f(e["errors_report_misses_target_pct"]), f(e["all_reports_miss_target_pct"])])
if rows:
    out += ["SLAKE report coverage of the queried target:", ""]
    table(["Reasoner", "Perceiver", "Errors whose report misses the target (%)", "All reports that miss the target (%)"], rows)

Cj = J.get("C", {})
out += ["## C. What two readers share: matched within-model contrasts (Δφ)", ""]
for s, sl in SETS.items():
    con = (Cj.get(s) or {}).get("contrasts") or {}
    if not con:
        continue
    rows = []
    for name in ("sampling only", "role", "rendering", "reference cases", "report", "perceiver", "reasoner", "model"):
        d = con.get(name) or {}
        rows.append([name, f(d.get("mean"), 3, sign=name != "sampling only")] +
                    ["; ".join(f"{NAME.get(k, k)} {f(v, 3, sign=name != 'sampling only')}" for k, v in sorted(d.items()) if k != "mean")])
    out += [f"{sl} (items {Cj[s]['n_items']}, reader slots {Cj[s]['n_slots']}):", ""]
    table(["Component", "Mean over models", "By model or model pair"], rows)
out += ["Regression summary (protocol section 7; additive, one intercept per reasoner pair):", ""]
rows = []
for s, sl in SETS.items():
    t = (Cj.get(s) or {}).get("terms") or {}
    rows.append([sl] + [f(t.get(k), 3, sign=True) for k in ("different perceiver", "image vs report", "different rendering",
                                                              "different role", "different reference cases", "different report")] +
                [f(((Cj.get(s) or {}).get("different_reasoner") or {}).get("mean"), 3, sign=True)])
table(["Set", "Perceiver", "Image vs report", "Rendering", "Role", "Reference cases", "Report", "Reasoner (mean)"], rows)

Mj = J.get("M", {})
out += ["## C4. Reference-case memory", ""]
rows = []
for k, d in Mj.items():
    m, s = k.split("|")
    rows.append([SETS[s], NAME[m], f(d.get("single_none")), f(d.get("single_shared-image")), f(d.get("single_shared-text")),
                 f(d.get("panel_none")), f(d.get("phi_none"), 3)] +
                [f"{f(d.get('panel_' + c))}; φ {f(d.get('phi_' + c), 3)}" for c in ("shared-image", "private-image", "shared-text", "private-text")])
table(["Set", "Model", "Single none", "Single shared image", "Single shared text", "Panel none", "φ none",
       "Shared image: panel; φ", "Private image", "Shared text", "Private text"], rows)

out += ["## D. Open-weight models", ""]
rows = []
for m in D.get("models", []):
    for s, sl in SETS.items():
        d = D.get(f"{m}|{s}") or {}
        if d:
            rows.append([NAME[m], sl, f(d.get("acc_real")), f(d.get("acc_blank")), f(d.get("acc_res256")), f(d.get("acc_res128")),
                         f(d.get("visual_reliance"), 2), f(d.get("visual_reliance_median"), 2)])
table(["Model", "Set", "Accuracy image (%)", "Accuracy gray (%)", "256 px", "128 px", "Visual reliance, mean", "median"], rows)
pairs = D.get("cross_model_pairs") or {}
rows = [[SETS[k.split("|")[0]], NAME[k.split("|")[1]], NAME[k.split("|")[2]], f(v["phi"], 3), f(v["phi_over_max"], 3),
         "yes" if v["shared_encoder"] else "no"] for k, v in pairs.items()]
table(["Set", "Model 1", "Model 2", "φ", "φ/φ_max", "Shared encoder"], rows)
link = D.get("api_link") or {}
rows = [[SETS[s], f(v["spearman_consensus_vs_reliance"], 3), str(v["n_items"]), f(v["reliance_on_consensus_error_items"], 2),
         f(v["reliance_on_other_items"], 2)] for s, v in link.items()]
table(["Set", "Spearman ρ (API consensus errors vs open-weight visual reliance)", "Items",
       "Median reliance, consensus-error items", "Median reliance, other items"], rows)

p = ROOT / "paper" / "radiology" / "numbers.md"
p.write_text("\n".join(out))
print(p, len(out), "lines")
