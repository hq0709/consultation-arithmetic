def f(ci, nd=1, sign=False):
    if not ci:
        return "–"
    if isinstance(ci, (int, float)):
        return f"{ci:+.{nd}f}" if sign else f"{ci:.{nd}f}"
    e, lo, hi = ci
    fmt = (lambda v: f"{v:+.{nd}f}") if sign else (lambda v: f"{v:.{nd}f}")
    return f"{fmt(e)} [{fmt(lo)}, {fmt(hi)}]"


TABLES = []                                     # (caption, head, rows) for the LaTeX supplement


def table(head, rows, caption=None, key=2):
    out.append("| " + " | ".join(head) + " |")
    out.append("|" + "---|" * len(head))
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    out.append("")
    if caption:
        TABLES.append((caption, head, rows, key))


def tex(x):
    """Markdown cell -> LaTeX cell."""
    import re
    x = (x.replace("%", "\\%").replace("&", "\\&").replace("_max", "$_{\\max}$").replace("N_eff", "$N_{\\mathrm{eff}}$")
         .replace("Δφ", "$\\Delta\\phi$").replace("φ", "$\\phi$").replace("ρ", "$\\rho$").replace("≤", "$\\le$")
         .replace("−", "$-$"))
    return re.sub(r"(?<![A-Za-z0-9.])-(?=\d)", "$-$", x)


def wrap(h, width=12):
    """Header text broken into lines of about `width` characters (LaTeX line breaks inside makecell)."""
    lines, cur = [], ""
    for w in h.split():
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur); cur = w
        else:
            cur = (cur + " " + w).strip()
    lines.append(cur)
    return "\\\\".join(tex(x) for x in lines)


def latex_tables(max_cols=6):
    """One booktabs table per digest table; tables wider than max_cols are split into column groups
    that repeat the two key columns, so no table needs shrinking below the text size."""
    L = ["% Generated by experiments/radiology_numbers.py. Do not edit by hand.", ""]
    for cap, head, rows, key in TABLES:
        data = len(head) - key
        step = max_cols - 2
        groups = [list(range(key + i, min(len(head), key + i + step))) for i in range(0, data, step)]
        for gi, cols in enumerate(groups):
            idx = list(range(key)) + cols
            c = tex(cap) if gi == 0 else tex(cap.split(":")[0].split(".")[0]) + " (continued)."
            L += ["\\begin{table}[!htbp]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{4pt}", f"\\caption{{{c}}}",
                  "\\begin{tabular}{" + "l" * key + "c" * len(cols) + "}", "\\toprule",
                  " & ".join("\\makecell{" + wrap(head[i]) + "}" for i in idx) + " \\\\", "\\midrule"]
            cell = lambda i, v: tex(v) if i < key or " [" not in v else "\\makecell{" + tex(v).replace(" [", "\\\\{}[", 1) + "}"
            L += [" & ".join(cell(i, r[i]) for i in idx) + " \\\\" for r in rows]
            L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)


