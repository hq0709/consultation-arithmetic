"""Round-3 candidate main-text tables of the CVPR paper, generated from the result files.

  python experiments/cvpr_fig/r3/tables_r3.py      # -> paper/cvpr/figure_candidates/round3/tables_r3.tex

No number is typed by hand: every cell comes from results/cvpr_nmi.json
(experiments/cvpr_fig/extract_nmi.py) or results/imaging_v2_C.json (experiments/imaging_v2_analysis.py C).
A cell whose run has not finished prints "--"; a quantity that an architecture does not define prints
"n/a". Re-running the extraction and this script after the grid completes fills every cell.

Candidates (each a complete float; \\candidhead{ID}{...} prints a heading in the preview only):
  T1a  main results: accuracy of SAS and the four MAS architectures, models x data sets (table*)
  T1b  multi-agent gain over SAS averaged over data sets, with a significance count (table)
  T1b-wide  the same gains per data set plus the mean (table*)
  T1c  architecture summary in the style of NMI Table 2: accuracy, gain, calls, tokens, accuracy per
       1K tokens, error correlation (table)
  T2a  matched component contrasts, mean change in error correlation with 95% CI (table)
  T2b  the same with an inline bar per cell (table)
Paper preamble needs booktabs, multirow, makecell and colortbl (or xcolor with the table option).
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
NMI = json.loads((ROOT / "results" / "cvpr_nmi.json").read_text())
C = json.loads((ROOT / "results" / "imaging_v2_C.json").read_text())
OUT = ROOT / "paper" / "cvpr" / "figure_candidates" / "round3" / "tables_r3.tex"

FAMILIES = [("OpenAI", ["gpt-5-nano", "gpt-5-mini", "gpt-5"]),
            ("Google", ["gemini-3.5-flash-lite", "gemini-3.7-flash"]),
            ("Anthropic", ["claude-haiku-4-5-20251001", "claude-sonnet-5"]),
            ("Qwen", ["qwen3.8-flash", "qwen3.8-max-0902"])]
NAME = {"gpt-5-nano": "GPT-5 nano", "gpt-5-mini": "GPT-5 mini", "gpt-5": "GPT-5",
        "gemini-3.5-flash-lite": "Gemini 3.5 Flash-Lite", "gemini-3.7-flash": "Gemini 3.7 Flash",
        "claude-haiku-4-5-20251001": "Claude Haiku 4.5", "claude-sonnet-5": "Claude Sonnet 5",
        "qwen3.8-flash": "Qwen 3.8 Flash", "qwen3.8-max-0902": "Qwen 3.8 Max"}
SETS = [("vqarad", "VQA-RAD"), ("slake", "SLAKE"), ("mxqa_mm_rad", "MedXpertQA-MM")]
SET_SHORT = {"vqarad": "VQA", "slake": "SLK", "mxqa_mm_rad": "MXQ"}
MAS = ["Independent", "Centralized", "Decentralized", "Hybrid"]
ALL = ["SAS"] + MAS
SHORT = {"SAS": "SAS", "Independent": "Ind.", "Centralized": "Cen.", "Decentralized": "Dec.", "Hybrid": "Hyb."}
N = 9                                            # MAS size of the main results
SC_MODELS = ["gpt-5-mini", "gemini-3.7-flash", "claude-haiku-4-5-20251001", "qwen3.8-flash"]
CONTRASTS = [("role", "Role"), ("rendering", "Contrast adjustment"), ("reference cases", "In-context examples"),
             ("report", "Report"), ("perceiver", "Perception module"), ("reasoner", "Reasoning module"),
             ("model", "Model")]
MISSING, UNDEF = "--", "n/a"


# ---------------------------------------------------------------- formatting
def num(v, nd=1):
    if v is None:
        return MISSING
    s = f"{v:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return s.replace("-", "$-$")


def est(ci):
    return ci[0] if isinstance(ci, list) else ci


def excludes_zero(ci):
    return isinstance(ci, list) and (ci[1] > 0 or ci[2] < 0)


def acc(m, s, arch):
    a = NMI["arch"].get(f"{m}|{s}") or {}
    return est(a.get("SAS" if arch == "SAS" else f"{arch}|{N}"))


def gain(m, s, arch):
    a = NMI["arch"].get(f"{m}|{s}") or {}
    return a.get(f"{arch}|{N}|gain")


def colored(v, txt, sig=True):
    """Sign colour for a gain (pp); grey when the interval includes zero."""
    if v is None:
        return txt
    if not sig:
        return r"\textcolor{gainns}{" + txt + "}"
    if round(v, 1) > 0:
        return r"\textcolor{gainpos}{" + txt + "}"
    if round(v, 1) < 0:
        return r"\textcolor{gainneg}{" + txt + "}"
    return txt


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def family_rows(cells_of, ncols, multirow=True):
    """Rows grouped by family: a multirow family cell or an italic family row before each group."""
    L = []
    for gi, (fam, models) in enumerate(FAMILIES):
        if gi:
            L.append(r"\midrule")
        if not multirow:
            L.append(r"\multicolumn{%d}{@{}l}{\textit{%s}} \\" % (ncols, fam))
        for k, m in enumerate(models):
            lead = []
            if multirow:
                lead = [r"\multirow{%d}{*}{%s}" % (len(models), fam) if k == 0 else ""]
            L.append(" & ".join(lead + [NAME[m]] + cells_of(m)) + r" \\")
    return L


HEAD = r"""%% Generated by experiments/cvpr_fig/r3/tables_r3.py. Do not edit by hand.
\providecommand{\candidhead}[2]{}
\providecolor{gainpos}{RGB}{26,122,64}
\providecolor{gainneg}{RGB}{178,52,48}
\providecolor{gainns}{RGB}{125,125,125}
\providecolor{sasgray}{gray}{0.92}
\providecolor{barphi}{RGB}{150,150,150}
\providecolor{bardphi}{RGB}{47,93,140}
"""
TEX = [HEAD]


# ---------------------------------------------------------------- T1a main results (accuracy)
def t1a():
    def cells(m):
        out = []
        for s, _ in SETS:
            vals = {a: acc(m, s, a) for a in ALL}
            have = [round(v, 1) for v in vals.values() if v is not None]
            best = max(have) if len(have) > 1 else None
            for a in ALL:
                v = vals[a]
                t = num(v)
                if v is not None and best is not None and round(v, 1) == best:
                    t = r"\textbf{" + t + "}"
                if a == "SAS":
                    t = r"\cellcolor{sasgray}" + t
                out.append(t)
        return out
    head2 = " & ".join(["Family", "Model"] + [(r"\cellcolor{sasgray}" if a == "SAS" else "") + SHORT[a]
                                               for _ in SETS for a in ALL])
    L = [r"\begin{table*}[t]", r"\candidhead{T1a}{Main results: accuracy of the five architectures across the capability ladder}",
         r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{3.1pt}",
         r"\caption{\textbf{Accuracy of the single-agent system and four multi-agent architectures across the capability "
         r"ladder.} Accuracy (\%) of the single-agent system (SAS, shaded) and of the Independent (Ind.), Centralized "
         r"(Cen.), Decentralized (Dec.) and Hybrid (Hyb.) MAS of 9 agents with original images (250 items per data set). "
         r"Bold: best architecture per model and data set. Models are grouped by family in order of capability. "
         r"Item-bootstrap 95\% CIs are in the supplement; " + MISSING + r" marks runs in progress.}",
         r"\label{tab:main-acc}",
         r"\begin{tabular}{@{}ll" + "c" * (5 * len(SETS)) + r"@{}}", r"\toprule",
         " & ".join(["", ""] + [r"\multicolumn{5}{c}{%s}" % lab for _, lab in SETS]) + r" \\",
         "".join(r"\cmidrule(lr){%d-%d}" % (3 + 5 * i, 7 + 5 * i) for i in range(len(SETS))),
         head2 + r" \\", r"\midrule"]
    L += family_rows(cells, 2 + 5 * len(SETS))
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    TEX.append("\n".join(L))


# ---------------------------------------------------------------- T1b gains, averaged over data sets
def t1b():
    def cells(m):
        sas = mean([acc(m, s, "SAS") for s, _ in SETS]) if all(acc(m, s, "SAS") is not None for s, _ in SETS) else None
        out = [num(sas)]
        for a in MAS:
            g = [gain(m, s, a) for s, _ in SETS]
            if any(x is None for x in g):
                out.append(MISSING)
                continue
            mu = mean([est(x) for x in g])
            k = sum(1 for x in g if excludes_zero(x) and (est(x) > 0) == (mu > 0))
            out.append(colored(mu, num(mu) + r"$^{%d}$" % k, sig=k > 0))
        return out
    L = [r"\begin{table}[t]", r"\candidhead{T1b}{Multi-agent gain over SAS, averaged over the three data sets}",
         r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2.6pt}",
         r"\caption{\textbf{Multi-agent gain over the single-agent system, by model and architecture.} Mean accuracy of the "
         r"single-agent system (SAS, \%) and mean gain of each MAS of 9 agents over SAS (pp), averaged over VQA-RAD, "
         r"SLAKE and MedXpertQA-MM. Superscript: data sets (of 3) whose paired item-bootstrap 95\% CI excludes zero "
         r"in the direction of the mean; green, gain; red, loss; grey, no data set with such an interval. "
         + MISSING + r" marks runs in progress.}",
         r"\label{tab:main-gain}",
         r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
         r" & & \multicolumn{4}{c}{Gain over SAS (pp)} \\", r"\cmidrule(l){3-6}",
         " & ".join(["Model", "SAS (\\%)"] + [SHORT[a] for a in MAS]) + r" \\", r"\midrule"]
    L += family_rows(cells, 6, multirow=False)
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    TEX.append("\n".join(L))


# ---------------------------------------------------------------- T1b-wide gains per data set
def t1b_wide():
    def cells(m):
        out = []
        for a in MAS:
            g = [gain(m, s, a) for s, _ in SETS]
            for x in g:
                out.append(MISSING if x is None else colored(est(x), (r"\textbf{%s}" if excludes_zero(x) else "%s")
                                                             % num(est(x)), sig=excludes_zero(x)))
            mu = mean([est(x) for x in g]) if all(x is not None for x in g) else None
            out.append(MISSING if mu is None else r"\textit{" + num(mu) + "}")
        return out
    ncol = 2 + 4 * len(MAS)
    L = [r"\begin{table*}[t]", r"\candidhead{T1b-wide}{Multi-agent gain over SAS per data set and on average}",
         r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2.5pt}",
         r"\caption{\textbf{Multi-agent gain over the single-agent system per data set.} Accuracy of each MAS of 9 "
         r"agents minus SAS accuracy (pp) on VQA-RAD (VQA), SLAKE (SLK) and MedXpertQA-MM (MXQ), and the mean over "
         r"the three (italic). Bold and coloured: paired item-bootstrap 95\% CI excludes zero (green, gain; red, "
         r"loss); grey: CI includes zero. " + MISSING + r" marks runs in progress.}",
         r"\label{tab:main-gain-wide}",
         r"\begin{tabular}{@{}ll" + "c" * (4 * len(MAS)) + r"@{}}", r"\toprule",
         " & ".join(["", ""] + [r"\multicolumn{4}{c}{%s}" % a for a in MAS]) + r" \\",
         "".join(r"\cmidrule(lr){%d-%d}" % (3 + 4 * i, 6 + 4 * i) for i in range(len(MAS))),
         " & ".join(["Family", "Model"] + [x for _ in MAS for x in [SET_SHORT[s] for s, _ in SETS] + ["Mean"]]) + r" \\",
         r"\midrule"]
    L += family_rows(cells, ncol)
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    TEX.append("\n".join(L))


# ---------------------------------------------------------------- T1c architecture summary (NMI Table 2 style)
def t1c():
    systems = {a: {k for k, v in NMI["arch"].items() if (v.get("SAS") if a == "SAS" else v.get(f"{a}|{N}")) is not None}
               for a in ALL}
    present = [a for a in ALL if systems[a]]
    common = sorted(set.intersection(*(systems[a] for a in present))) if present else []
    rows = []
    for a in ALL:
        if a not in present or not common:
            rows.append([a, MISSING, MISSING, MISSING, MISSING, MISSING, MISSING, MISSING])
            continue
        accs = [acc(*k.split("|"), a) for k in common]
        if a == "SAS":
            g_txt = "ref."
        else:
            g = [est(NMI["arch"][k][f"{a}|{N}|gain"]) for k in common]
            g_txt = r"\makecell{" + num(mean(g)) + r"\\{\tiny " + num(min(g)) + " to " + num(max(g)) + "}}"
        cost = [NMI["cost"].get(k, {}).get(a) for k in common]
        if all(c is not None for c in cost):
            calls = num(mean([c["calls"] for c in cost]))
            tok = [(c["in_tok"] + c["out_tok"]) for c in cost]
            tok_txt = num(mean(tok) / 1000, 1)
            eff = num(mean([c["acc"] / (t / 1000) for c, t in zip(cost, tok)]), 1)
        else:
            calls = tok_txt = eff = MISSING
        if a == "Independent":
            ph = [(NMI["scaling"].get(k) or {}).get("phi") for k in common]
            ph_txt = num(mean(ph), 3) if all(p is not None for p in ph) else MISSING
        elif a == "Decentralized":
            ph = [((NMI["debate"].get(k) or {}).get("phi") or [None])[-1] for k in common]
            ph_txt = num(mean(ph), 3) if all(p is not None for p in ph) else MISSING
        else:
            ph_txt = UNDEF
        rows.append([a, str(len(common)), num(mean(accs)), g_txt, calls, tok_txt, eff, ph_txt])
    L = [r"\begin{table}[t]", r"\candidhead{T1c}{Architecture summary in the style of NMI Table 2}",
         r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2.4pt}",
         r"\caption{\textbf{Every multi-agent architecture multiplies the calls and tokens spent per item.} Means over the model "
         r"$\times$ data-set systems that every listed architecture has completed ($n$): accuracy (\%), gain over the "
         r"single-agent system (pp; below, range over systems), model calls and tokens (thousands, input plus output) "
         r"per item, accuracy per 1K tokens, and the error correlation $\phi$ of the answers that are aggregated "
         r"(Independent: the 9 agents' answers; Decentralized: final answers after debate; " + UNDEF + r": a single "
         r"final answer). MAS of 9 agents, original images. " + MISSING + r" marks runs in progress.}",
         r"\label{tab:arch-summary}",
         r"\begin{tabular}{@{}lccccccc@{}}", r"\toprule",
         r"Architecture & $n$ & Acc. & \makecell{Gain\\(pp)} & Calls & \makecell{Tokens\\(K)} & "
         r"\makecell{Acc./1K\\tokens} & $\phi$ \\", r"\midrule"]
    for r in rows:
        L.append(" & ".join(r) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    TEX.append("\n".join(L))


# ---------------------------------------------------------------- T2 component contrasts
def contrast_cells(bar=False):
    sc_rows, d_rows = [], []

    def cell(ci, nd, scale_color):
        if ci is None:
            return MISSING
        e, lo, hi = ci
        top = num(e, nd)
        if bar:
            L_mm = min(abs(e), 1.0) * 6.5
            top = (r"\makebox[6.8mm][l]{\textcolor{%s}{\rule{%.2fmm}{1.05ex}}}" % (scale_color, L_mm)) + top
        return r"\makecell{" + top + r"\\{\tiny[" + num(lo, nd) + ", " + num(hi, nd) + "]}}"
    for m in SC_MODELS:
        sc_rows.append([NAME[m]] + [cell((C[s]["contrasts"].get("sampling only") or {}).get(m), 3, "barphi")
                                    for s, _ in SETS])
    for key, lab in CONTRASTS:
        cs = []
        for s, _ in SETS:
            v = (C[s]["contrasts"].get(key) or {}).get("mean")
            if v is None or (v[0] == v[1] == v[2] == 0):
                cs.append(UNDEF if key == "reference cases" else MISSING)
            else:
                cs.append(cell(v, 3, "bardphi"))
        d_rows.append([lab] + cs)
    return sc_rows, d_rows


def t2(bar):
    sc_rows, d_rows = contrast_cells(bar)
    cid = "T2b" if bar else "T2a"
    head = ("Matched component contrasts with an inline bar per cell" if bar
            else "Matched component contrasts (replaces the dot-ladder figure)")
    cap = (r"\caption{\textbf{Changing the model lowers error correlation more than any other tested contrast.} "
           r"Top: error correlation $\phi$ of 9 self-consistency agents of one model. Bottom: mean change in "
           r"error correlation ($\Delta\phi$) when two agents do not share the named component, averaged over models "
           r"(or model pairs), with item-bootstrap 95\% CI. " + UNDEF + r": in-context examples were run on VQA-RAD "
           r"and SLAKE only."
           + (r" Bars: $|\phi|$ or $|\Delta\phi|$ on one 0 to 1 scale (grey, $\phi$; blue, $\Delta\phi$)." if bar else "")
           + "}")
    L = [r"\begin{table}[t]", r"\candidhead{%s}{%s}" % (cid, head), r"\centering", r"\scriptsize",
         r"\setlength{\tabcolsep}{3pt}", cap, r"\label{tab:contrasts%s}" % ("-bars" if bar else ""),
         r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
         " & ".join([""] + [lab for _, lab in SETS]) + r" \\", r"\midrule",
         r"\multicolumn{4}{@{}l}{\textit{Self-consistency $\phi$}} \\"]
    L += [" & ".join(r) + r" \\" for r in sc_rows]
    L += [r"\midrule", r"\multicolumn{4}{@{}l}{\textit{$\Delta\phi$ when agents do not share}} \\"]
    L += [" & ".join(r) + r" \\" for r in d_rows]
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    TEX.append("\n".join(L))


def main():
    t1a(); t1b(); t1b_wide(); t1c(); t2(False); t2(True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(TEX))
    import re
    for t in TEX[1:]:
        cid = re.search(r"\\candidhead\{([^}]*)\}", t).group(1)
        n_missing = len(re.findall(r"(?m)(?:(?<=& )|^)--(?= &| \\\\)", t))
        print(f"{cid:9s} cells still {MISSING}: {n_missing}")
    print(OUT)


if __name__ == "__main__":
    main()
